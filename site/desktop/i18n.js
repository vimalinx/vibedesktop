import { store } from "./util.js";

const saved = store.get("lang", null);
export const lang = saved === "zh" || saved === "en"
  ? saved
  : (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";

document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

export function setLang(next) {
  store.set("lang", next);
  try {
    sessionStorage.setItem("vd.booted", "1");
  } catch {
    /* the boot animation simply plays again */
  }
  location.reload();
}

/** Pick the current language from a { zh, en } pair. */
export const pick = (pair) => (pair && typeof pair === "object" ? pair[lang] ?? pair.en : pair);

export function t(key, vars) {
  const value = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return vars ? value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? "")) : value;
}

